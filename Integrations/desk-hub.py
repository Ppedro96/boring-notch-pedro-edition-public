#!/usr/bin/env python3
"""Notch desktop broker: allowlisted SSH workers, persistent FIFO jobs, bounded search."""
import base64, concurrent.futures, tempfile, fcntl, hashlib, json, os, re, shutil, subprocess, sys, time, uuid
from pathlib import Path
ROOT=Path.home()/'.local/share/pedro-notch'
STATE=ROOT/'desk-jobs'; RESULTS=Path.home()/'Downloads/Insight Notch'
HOSTS={'mac':None,'x99':'x99','alienware':'alienware'}
REMOTE={'x99':'/home/user/.local/share/insight-notch/desk-worker.py','alienware':'C:/Users/user/.local/share/insight-notch/desk-worker.py'}
PYTHON={'x99':'python3','alienware':'python'}
ENV=dict(os.environ,PATH='/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin')

def save(path,value):
    path.parent.mkdir(mode=0o700,parents=True,exist_ok=True)
    temp=path.with_suffix('.tmp-'+uuid.uuid4().hex);temp.write_text(json.dumps(value,ensure_ascii=False));temp.replace(path)

def checkhost(host):
    if host not in HOSTS: raise ValueError('Máquina inválida')

def rpc(host,request,timeout=20):
    checkhost(host)
    if host=='mac': args=['/usr/bin/python3',str(Path(__file__).with_name('desk-worker.py'))]
    else:
        # Fixed paths/code only on remote command line. Every user value travels over JSON stdin.
        script="import runpy;runpy.run_path("+repr(REMOTE[host])+",run_name='__main__')"
        code=base64.b64encode(script.encode()).decode()
        args=['/usr/bin/ssh','-o','BatchMode=yes','-o','ConnectTimeout=5',host,
              PYTHON[host]+' -c "import base64;exec(base64.b64decode(\''+code+'\'))"']
    result=subprocess.run(args,input=json.dumps(request),capture_output=True,text=True,timeout=timeout,env=ENV)
    try: value=json.loads(result.stdout.strip().lstrip('\ufeff'))
    except ValueError: raise RuntimeError((result.stderr.strip() or 'Worker indisponível')[-700:])
    if not value.get('ok'): raise RuntimeError(value.get('error','Falha no worker'))
    return value

def capabilities(host):
    try: return dict(id=host,online=True,**rpc(host,dict(command='capabilities')))
    except Exception as error: return dict(id=host,online=False,error=str(error))

def scp(host,source,dest,upload=False,cancel=None):
    if host=='mac':
        with open(source,'rb') as src,open(dest,'xb') as target:
            for chunk in iter(lambda:src.read(4*1024*1024),b''):
                if cancel and cancel.exists():raise InterruptedError('Cancelado')
                target.write(chunk)
        return
    source = source.replace('\\','/') if not upload else source
    dest = dest.replace('\\','/') if upload else dest
    remote=dest if upload else source
    # Remote paths are generated by our worker; never forward arbitrary filenames to a remote shell.
    if not re.fullmatch(r'(?:/home/user|C:/Users/user)/\.local/share/insight-notch/jobs/[a-f0-9]{32}/[A-Za-z0-9_.-]+',remote):
        raise ValueError('Caminho remoto inválido')
    args=['/usr/bin/scp','-q','-o','BatchMode=yes','-o','ConnectTimeout=6']
    args += [source,host+':'+dest] if upload else [host+':'+source,dest]
    if cancel:
        with tempfile.TemporaryFile(mode='w+') as errors:
            child=subprocess.Popen(args,stdout=subprocess.DEVNULL,stderr=errors)
            deadline=time.monotonic()+3600
            try:
                while child.poll() is None:
                    if cancel.exists():raise InterruptedError('Cancelado')
                    if time.monotonic()>deadline:raise TimeoutError('Tempo limite de envio')
                    time.sleep(.2)
            finally:
                if child.poll() is None:child.terminate();child.wait(timeout=5)
            if child.returncode:errors.seek(0);raise RuntimeError(errors.read()[-500:])
    else:
        result=subprocess.run(args,capture_output=True,text=True,timeout=3600)
        if result.returncode:raise RuntimeError(result.stderr[-500:])

def digest(path):
    h=hashlib.sha256()
    with Path(path).open('rb') as f:
        for chunk in iter(lambda:f.read(4*1024*1024),b''):h.update(chunk)
    return h.hexdigest()

def retrieve(host,remote,expected,name):
    RESULTS.mkdir(parents=True,exist_ok=True)
    name=Path(name).name
    target=RESULTS/(Path(name).stem+'-'+uuid.uuid4().hex[:8]+Path(name).suffix)
    partial=target.with_suffix(target.suffix+'.partial')
    try:
        scp(host,remote,str(partial))
        if digest(partial)!=expected: raise ValueError('Falha na verificação do arquivo recebido')
        partial.replace(target)
    finally:
        if partial.exists():partial.unlink()
    return str(target)

def entries():
    STATE.mkdir(mode=0o700,parents=True,exist_ok=True)
    found=[]
    for path in STATE.glob('*.json'):
        try:found.append(json.loads(path.read_text()))
        except (OSError,ValueError):pass
    ordered=sorted(found,key=lambda v:v['created'],reverse=True)
    return [v for v in ordered if v['state'] in ('waiting','running')] + [v for v in ordered if v['state'] not in ('waiting','running')][:60]

def jobpath(ident):
    if not re.fullmatch('[a-f0-9]{32}',ident):raise ValueError('Trabalho inválido')
    return STATE/(ident+'.json')

def queue(host):
    checkhost(host)
    STATE.mkdir(mode=0o700,parents=True,exist_ok=True)
    with (STATE/('queue-'+host+'.lock')).open('a') as lock:
        try:fcntl.flock(lock,fcntl.LOCK_EX|fcntl.LOCK_NB)
        except BlockingIOError:return
        while True:
            pending=sorted([v for v in entries() if v['state'] in ('waiting','running') and v['host']==host],key=lambda v:v['created'])
            if not pending:return
            job=pending[0]; path=jobpath(job['id']); host=job['host'];prepared=job.get('remoteStarted',False)
            def update(**values):job.update(values,updated=time.time());save(path,job)
            try:
                if path.with_suffix('.cancel').exists():update(state='cancelled',detail='Cancelado');continue
                update(state='running',detail='Enviando arquivo' if not prepared else 'Retomando acompanhamento')
                if not prepared:
                    value=rpc(host,dict(command='prepare',id=job['id'],extension=Path(job['source']).suffix))
                    scp(host,job['source'],value['path'],upload=True,cancel=path.with_suffix('.cancel'))
                    # A cancel requested during upload must not start an expensive conversion.
                    if path.with_suffix('.cancel').exists():update(state='cancelled',detail='Cancelado');continue
                    rpc(host,dict(command='start',id=job['id'],operation=job['operation']))
                    update(remoteStarted=True)
                failures=0
                while True:
                    if path.with_suffix('.cancel').exists():
                        rpc(host,dict(command='cancel',id=job['id']))
                        update(state='cancelled',detail='Cancelado');break
                    try:
                        status=rpc(host,dict(command='status',id=job['id']));failures=0
                    except Exception:
                        failures+=1
                        if failures>8:raise
                        update(detail='Reconectando à máquina');time.sleep(3);continue
                    if status['state']=='waiting' and time.time()-job['created']>90:raise RuntimeError('O worker não iniciou; confira a sessão da máquina')
                    if status['state']=='completed':
                        update(detail='Recebendo e verificando resultado',progress=99)
                        suffix=Path(status['output']).suffix
                        output=retrieve(host,status['output'],status['sha256'],Path(job['source']).stem+suffix)
                        update(state='completed',progress=100,detail='Concluído',output=output)
                        try:rpc(host,dict(command='release',id=job['id']))
                        except Exception:pass
                        break
                    update(state=status['state'],progress=status.get('progress',0),detail=status.get('detail',''))
                    if status['state'] in ('failed','cancelled'):break
                    time.sleep(1)
            except Exception as error:update(state='cancelled' if isinstance(error,InterruptedError) else 'failed',detail=str(error)[-800:])

def start_queue():
    ROOT.mkdir(mode=0o700,parents=True,exist_ok=True)
    with (ROOT/'desk-queue.log').open('a') as log:
        for host in {j['host'] for j in entries() if j['state'] in ('waiting','running')}:
            subprocess.Popen(['/usr/bin/python3',str(Path(__file__).resolve()),'queue',host],stdin=subprocess.DEVNULL,stdout=log,stderr=log,start_new_session=True,env=ENV)

def main(r):
    cmd=r['command']
    if cmd=='capabilities':
        with concurrent.futures.ThreadPoolExecutor(max_workers=3) as pool:return dict(ok=True,hosts=list(pool.map(capabilities,HOSTS)))
    if cmd=='search':
        hosts=list(HOSTS) if r.get('host','all')=='all' else [r['host']]
        def run(host):
            try:return host,rpc(host,dict(command='search',query=r['query']),timeout=15)
            except Exception as error:return host,dict(error=str(error))
        with concurrent.futures.ThreadPoolExecutor(max_workers=3) as pool:values=list(pool.map(run,hosts))
        return dict(ok=True,results=[dict(v,host=h) for h,data in values for v in data.get('results',[])],warnings=[h+': '+data.get('error','Busca parcial; refine o nome') for h,data in values if data.get('error') or data.get('truncated')])
    if cmd=='fetch':
        host=r['host'];checkhost(host)
        value=rpc(host,dict(command='stage',root=r['root'],relative=r['relative']),timeout=3600)
        output=retrieve(host,value['path'],value['sha256'],value['name'])
        try:rpc(host,dict(command='release',id=value['id']))
        except Exception:pass
        return dict(ok=True,output=output)
    if cmd=='archive':
        archive=STATE/'archive';archive.mkdir(parents=True,exist_ok=True)
        for job in entries():
            if job['state'] not in ('waiting','running'):
                path=jobpath(job['id']);path.replace(archive/path.name)
        return dict(ok=True)
    if cmd=='jobs':
        values=entries()
        if any(j['state'] in ('waiting','running') for j in values):start_queue()
        return dict(ok=True,jobs=values)
    if cmd=='submit':
        host=r['host'];source=Path(r['source']).resolve()
        if host=='auto':
            feature='transcribe' if r['operation']=='transcribe' else 'ffmpeg'
            order=('mac','x99','alienware') if r['operation']=='audio' else ('x99','alienware','mac')
            available=[key for key in order if (lambda cap:cap.get('online') and cap.get(feature))(capabilities(key))]
            active=entries()
            host=min(available,key=lambda key:(sum(j['host']==key and j['state'] in ('waiting','running') for j in active),order.index(key))) if available else None
            if not host:raise ValueError('Nenhuma máquina disponível para esta tarefa')
        checkhost(host)
        if not source.is_file():raise ValueError('Selecione um arquivo local disponível')
        if r['operation'] not in ('audio','video','transcribe'):raise ValueError('Operação inválida')
        cap=capabilities(host)
        if not cap.get('online') or not cap.get('transcribe' if r['operation']=='transcribe' else 'ffmpeg'):raise ValueError('Recurso indisponível nesta máquina')
        ident=uuid.uuid4().hex;job=dict(id=ident,host=host,source=str(source),name=source.name,operation=r['operation'],state='waiting',progress=0,detail='Na fila',created=time.time(),updated=time.time())
        save(jobpath(ident),job);start_queue();return dict(ok=True,id=ident)
    if cmd=='cancel':
        path=jobpath(r['id']);job=json.loads(path.read_text());path.with_suffix('.cancel').touch()
        if job['state']=='waiting':job.update(state='cancelled',detail='Cancelado')
        save(path,job)
        if job.get('remoteStarted'):rpc(job['host'],dict(command='cancel',id=job['id']))
        return dict(ok=True)
    if cmd=='deskflow':
        return deskflow(r)
    raise ValueError('Comando inválido')

def deskflow(r):
    import importlib.util
    path=Path(__file__).with_name('lan-mouse-control.py')
    if path.exists():
        spec=importlib.util.spec_from_file_location('lan_mouse_control',path)
        module=importlib.util.module_from_spec(spec);spec.loader.exec_module(module)
        return module.main(r,legacy_deskflow)
    return legacy_deskflow(r)

def legacy_deskflow(r):
    import importlib.util
    spec=importlib.util.spec_from_file_location('deskflow_control',Path(__file__).with_name('deskflow-control.py'))
    module=importlib.util.module_from_spec(spec);spec.loader.exec_module(module)
    action=r.get('action','status')
    result=module.main(r)
    if action in ('start','stop'):
        problems=[]
        for host in ('x99','alienware'):
            try:rpc(host,dict(command='deskflow',action=action))
            except Exception as error:problems.append(host+': '+str(error))
        if problems:result['detail']=result.get('detail','')+' · '+' · '.join(problems)
    else:
        result['clients']={}
        for host in ('x99','alienware'):
            try:result['clients'][host]=rpc(host,dict(command='deskflow',action='status'))
            except Exception as error:result['clients'][host]=dict(error=str(error))
    return result

if __name__=='__main__':
    try:
        if len(sys.argv)>1 and sys.argv[1]=='queue':queue(sys.argv[2])
        else:print(json.dumps(main(json.load(sys.stdin)),ensure_ascii=False))
    except Exception as error:print(json.dumps(dict(ok=False,error=str(error)),ensure_ascii=False));sys.exit(1)
