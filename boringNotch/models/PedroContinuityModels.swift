import Foundation
import CryptoKit

/// Typed wire values keep protocol envelopes separate from nested desk job ids.
enum PedroContinuityValue: Codable, Equatable, Sendable {
    case string(String), number(Double), bool(Bool), object([String: Self]), array([Self]), null
    init(from decoder: Decoder) throws {
        let c = try decoder.singleValueContainer()
        if c.decodeNil() { self = .null }
        else if let v = try? c.decode(Bool.self) { self = .bool(v) }
        else if let v = try? c.decode(Double.self) { self = .number(v) }
        else if let v = try? c.decode(String.self) { self = .string(v) }
        else if let v = try? c.decode([String: Self].self) { self = .object(v) }
        else { self = .array(try c.decode([Self].self)) }
    }
    func encode(to encoder: Encoder) throws {
        var c = encoder.singleValueContainer()
        switch self {
        case .string(let v): try c.encode(v)
        case .number(let v): try c.encode(v)
        case .bool(let v): try c.encode(v)
        case .object(let v): try c.encode(v)
        case .array(let v): try c.encode(v)
        case .null: try c.encodeNil()
        }
    }
    var string: String { if case .string(let v) = self { return v }; return "" }
    var number: Double { if case .number(let v) = self { return v }; return 0 }
    var bool: Bool { if case .bool(let v) = self { return v }; return false }
    var object: [String: Self] { if case .object(let v) = self { return v }; return [:] }
}
typealias PedroContinuityPayload = [String: PedroContinuityValue]
struct PedroContinuityItem: Codable, Identifiable, Equatable, Sendable {
    let id: String
    let origin: String
    let updatedAt: Double
    let payload: PedroContinuityPayload
    func text(_ key: String) -> String { payload[key]?.string ?? "" }
    func number(_ key: String) -> Double { payload[key]?.number ?? 0 }
    func flag(_ key: String) -> Bool { payload[key]?.bool ?? false }
}
struct PedroContinuitySnapshot: Decodable, Sendable {
    let topic: String
    let revision: Int
    let items: [PedroContinuityItem]
    let initial: Bool?
    let cached: Bool?
    let replayed: Bool?
    let changed: [String]?
}
enum PedroContinuityPolicy {
    static func digest(_ data: Data) -> String { SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined() }
    // Shared portable identity is SHA-256 of exact UTF-8 text or original PNG bytes.
    static func isPrivate(types: [String]) -> Bool {
        types.contains { type in
            let t = type.lowercased()
            return ["concealed", "transient", "autogenerated", "password", "onepassword", "1password", "bitwarden", "keepass", "lastpass", "private"].contains { t.contains($0) }
        }
    }
    static func canActivate(_ item: PedroContinuityItem, snapshot: PedroContinuitySnapshot,
                            previous: PedroContinuityItem?, peer: String, now: Double) -> Bool {
        guard snapshot.initial == false, snapshot.cached == false, snapshot.replayed == false,
              snapshot.changed?.contains(item.id) == true, item.origin != peer,
              now - item.number("capturedAt") >= 0, now - item.number("capturedAt") <= 30 else { return false }
        return previous == nil || previous?.number("capturedAt") != item.number("capturedAt")
    }
    static func mayFinishClipboard(expectedEvent: Int, event: Int, expectedLocal: Int, local: Int, expectedChange: Int, change: Int) -> Bool {
        expectedEvent == event && expectedLocal == local && expectedChange == change
    }
    static func shouldCapture(fingerprint: String, suppressed: String?) -> Bool { fingerprint != suppressed }
    static func taskKey(peer: String, provider: String, session: String) -> String {
        peer + ":" + provider + "-" + digest(Data(session.utf8))
    }
    static func sharedTasksForDisplay(_ items: [PedroContinuityItem], peer: String) -> [PedroContinuityItem] {
        let terminalStatuses: Set<String> = ["completed", "done", "success", "failed", "error", "cancelled", "canceled"]
        return items.filter { $0.origin != peer }.sorted { lhs, rhs in
            let leftTerminal = terminalStatuses.contains(lhs.text("status").lowercased())
            let rightTerminal = terminalStatuses.contains(rhs.text("status").lowercased())
            if leftTerminal != rightTerminal { return !leftTerminal }
            let leftUpdated = lhs.number("updatedAt"), rightUpdated = rhs.number("updatedAt")
            if leftUpdated != rightUpdated { return leftUpdated > rightUpdated }
            return lhs.id < rhs.id
        }
    }
    static func taskStatusLabel(_ status: String) -> String {
        switch status {
        case "working", "running", "in_progress": return "Em andamento"
        case "queued", "pending": return "Na fila"
        case "waiting": return "Aguardando na origem"
        case "paused": return "Pausada"
        case "completed", "done", "success": return "Concluída"
        case "failed", "error": return "Falhou"
        case "cancelled", "canceled": return "Cancelada"
        case "cancelPending": return "Cancelamento solicitado"
        default: return "Estado indisponível"
        }
    }
    static func taskProgress(_ item: PedroContinuityItem) -> Double? {
        guard case .number(let value) = item.payload["progress"], value.isFinite else { return nil }
        return min(100, max(0, value))
    }
    static func isSharedAlert(source: String, id: String) -> Bool {
        !["mac", "ssh", "usage"].contains(source.lowercased()) && !["mac.", "ssh.", "usage."].contains(where: id.hasPrefix)
    }
    static func matchesAlert(_ item: PedroContinuityItem, id: String, hash: String) -> Bool {
        item.flag("dismissed") && item.text("alertId") == id && item.text("stateHash") == hash
    }
    static func mediaAvailable(_ item: PedroContinuityItem, now: Double) -> Bool {
        item.flag("available") && now >= item.number("updatedAt") && now - item.number("updatedAt") <= 35
    }
}
