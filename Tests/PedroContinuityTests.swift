import Foundation

@main struct PedroContinuityTests {
    @MainActor static func main() async throws {
        func check(_ condition: @autoclosure () -> Bool, _ message: String) {
            if !condition() { fatalError(message) }
        }
        let now = Date().timeIntervalSince1970
        let payload: PedroContinuityPayload = ["kind": .string("text"), "text": .string("  shared\n"), "capturedAt": .number(now), "pinned": .bool(false)]
        let item = PedroContinuityItem(id: "content", origin: "other", updatedAt: now, payload: payload)
        func snapshot(initial: Bool = false, cached: Bool = false, replayed: Bool = false, changed: [String] = ["content"]) -> PedroContinuitySnapshot {
            PedroContinuitySnapshot(topic: "clipboard", revision: 1, items: [item], initial: initial, cached: cached, replayed: replayed, changed: changed)
        }
        check(PedroContinuityPolicy.canActivate(item, snapshot: snapshot(), previous: nil, peer: "local", now: now), "Fresh remote copy must activate")
        for stale in [snapshot(initial: true), snapshot(cached: true), snapshot(replayed: true), snapshot(changed: [])] {
            check(!PedroContinuityPolicy.canActivate(item, snapshot: stale, previous: nil, peer: "local", now: now), "History/replay must not activate")
        }
        check(!PedroContinuityPolicy.canActivate(item, snapshot: snapshot(), previous: item, peer: "local", now: now), "Pin patch must not activate unchanged capture")
        check(!PedroContinuityPolicy.canActivate(item, snapshot: snapshot(), previous: nil, peer: "other", now: now), "Origin echo must not activate")
        check(!PedroContinuityPolicy.canActivate(item, snapshot: snapshot(), previous: nil, peer: "local", now: now + 31), "Expired copy must not activate")
        check(!PedroContinuityPolicy.canActivate(item, snapshot: snapshot(), previous: nil, peer: "local", now: now - 1), "Future copy must not activate")
        for type in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword", "org.keepass.private", "org.bitwarden.password"] {
            check(PedroContinuityPolicy.isPrivate(types: ["public.utf8-plain-text", type]), "Private MIME was accepted: \(type)")
        }
        check(!PedroContinuityPolicy.isPrivate(types: ["public.png", "public.utf8-plain-text"]), "Ordinary text/image rejected")
        check(PedroContinuityPolicy.digest(Data("a".utf8)) == "ca978112ca1bbdcafac231b39a23dc4da786eff8147c4e72b9807785afee48bb", "Portable SHA identity")
        check(PedroContinuityPolicy.digest(Data(" x\n".utf8)) != PedroContinuityPolicy.digest(Data("x".utf8)), "Whitespace identity must remain exact")
        let ack = PedroContinuityItem(id: "ack", origin: "other", updatedAt: now, payload: ["alertId": .string("service.a"), "stateHash": .string("v1"), "dismissed": .bool(true)])
        check(PedroContinuityPolicy.matchesAlert(ack, id: "service.a", hash: "v1"), "Matching acknowledgement")
        check(!PedroContinuityPolicy.matchesAlert(ack, id: "service.a", hash: "v2"), "Changed alert must resurface")
        for source in ["mac", "ssh", "usage"] { check(!PedroContinuityPolicy.isSharedAlert(source: source, id: "test"), "Local alert must not share") }
        let media = PedroContinuityItem(id: "other", origin: "other", updatedAt: now, payload: ["available": .bool(true), "updatedAt": .number(now)])
        check(PedroContinuityPolicy.mediaAvailable(media, now: now), "Fresh media")
        check(!PedroContinuityPolicy.mediaAvailable(media, now: now + 36), "Dead media must expire")
        check(!PedroContinuityPolicy.shouldCapture(fingerprint: "remote", suppressed: "remote"), "Content echo must not publish")
        check(PedroContinuityPolicy.shouldCapture(fingerprint: "new", suppressed: "remote"), "New local copy must publish")
        check(!PedroContinuityPolicy.mayFinishClipboard(expectedEvent: 1, event: 2, expectedLocal: 1, local: 1, expectedChange: 1, change: 1), "Slow image must not replace newer remote text")
        check(!PedroContinuityPolicy.mayFinishClipboard(expectedEvent: 1, event: 1, expectedLocal: 1, local: 2, expectedChange: 1, change: 1), "Slow image must not replace newer local capture")
        check(!PedroContinuityPolicy.mayFinishClipboard(expectedEvent: 1, event: 1, expectedLocal: 1, local: 1, expectedChange: 1, change: 2), "Unpolled local clipboard change wins")
        check(PedroContinuityPolicy.taskKey(peer: "a", provider: "codex", session: "same") != PedroContinuityPolicy.taskKey(peer: "b", provider: "codex", session: "same"), "Independent task origins")
        for (status, label) in [("working", "Em andamento"), ("running", "Em andamento"), ("queued", "Na fila"), ("waiting", "Aguardando na origem"), ("completed", "Concluída"), ("failed", "Falhou"), ("cancelled", "Cancelada"), ("cancelPending", "Cancelamento solicitado"), ("unknown", "Estado indisponível")] {
            check(PedroContinuityPolicy.taskStatusLabel(status) == label, "Remote task status must be readable in Portuguese")
        }
        func task(progress: PedroContinuityValue?) -> PedroContinuityItem {
            PedroContinuityItem(id: "task", origin: "other", updatedAt: now, payload: progress.map { ["progress": $0] } ?? [:])
        }
        check(PedroContinuityPolicy.taskProgress(task(progress: .number(42.5))) == 42.5, "Remote task progress must retain its reported percentage")
        check(PedroContinuityPolicy.taskProgress(task(progress: .number(100))) == 100, "Completed progress")
        check(PedroContinuityPolicy.taskProgress(task(progress: nil)) == nil, "Absent progress must not fabricate zero")
        check(PedroContinuityPolicy.taskProgress(task(progress: .string("50"))) == nil, "Non-numeric progress must not fabricate zero")
        check(PedroContinuityPolicy.taskProgress(task(progress: .number(.nan))) == nil, "Nonfinite progress must not reach the view")
        check(PedroContinuityPolicy.taskProgress(task(progress: .number(110))) == 100, "Progress view upper bound")
        check(PedroContinuityPolicy.taskProgress(task(progress: .number(-1))) == 0, "Progress view lower bound")
        func taskRow(_ id: String, origin: String, status: String, sourceTime: Double, envelopeTime: Double) -> PedroContinuityItem {
            PedroContinuityItem(id: id, origin: origin, updatedAt: envelopeTime, payload: ["status": .string(status), "updatedAt": .number(sourceTime)])
        }
        let taskRows = [
            taskRow("done", origin: "remote-a", status: "completed", sourceTime: 500, envelopeTime: 1),
            taskRow("b-working", origin: "remote-b", status: "working", sourceTime: 200, envelopeTime: 999),
            taskRow("a-waiting", origin: "remote-a", status: "waiting", sourceTime: 200, envelopeTime: 2),
            taskRow("cancel", origin: "remote-b", status: "cancelled", sourceTime: 600, envelopeTime: 1),
            taskRow("new-working", origin: "remote-a", status: "running", sourceTime: 300, envelopeTime: 1),
            taskRow("failed", origin: "remote-c", status: "failed", sourceTime: 700, envelopeTime: 1),
            taskRow("pending-cancel", origin: "remote-c", status: "cancelPending", sourceTime: 100, envelopeTime: 1),
            taskRow("own", origin: "local", status: "working", sourceTime: 9999, envelopeTime: 9999)
        ]
        let displayTasks = PedroContinuityPolicy.sharedTasksForDisplay(taskRows, peer: "local")
        check(displayTasks.map(\.id) == ["new-working", "a-waiting", "b-working", "pending-cancel", "failed", "cancel", "done"], "Active/waiting tasks precede terminal history, ordered by source time then stable id")
        check(PedroContinuityPolicy.sharedTasksForDisplay(Array(taskRows.reversed()), peer: "local") == displayTasks, "Task display order must not depend on hash/input order")
        check(Set(displayTasks.map(\.id)) == Set(taskRows.filter { $0.origin != "local" }.map(\.id)), "Display sorting must preserve all remote history")
        let wire = try JSONEncoder().encode(["ok": PedroContinuityValue.bool(true), "id": .string("outer"), "result": .object(["id": .string("job")])])
        let decoded = try JSONDecoder().decode(PedroContinuityPayload.self, from: wire)
        check(decoded["id"]?.string == "outer" && decoded["result"]?.object["id"]?.string == "job", "Desk nested correlation")
        try await transportTest()
        print("PASS: native continuity privacy/freshness/identity/alerts/media and persistent NDJSON multiplexing")
    }
    @MainActor static func transportTest() async throws {
        let directory = FileManager.default.temporaryDirectory.resolvingSymlinksInPath().appendingPathComponent("notch-native-test-" + UUID().uuidString)
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: directory) }
        let script = directory.appendingPathComponent("fixture.py")
        // This deliberately emits replies in reverse order and a large stderr stream.
        let fixture = #"""
import sys,json,time,subprocess,os,signal
print(json.dumps({'event':'connection','state':'online'}),flush=True)
sys.stderr.write('x'*100000);sys.stderr.flush()
held=None
for line in sys.stdin:
    r=json.loads(line)
    if r['op']=='hold': held=r;continue
    if r['op']=='exit': sys.exit(0)
    if r['op']=='crash': os._exit(3)
    if r['op']=='wait': continue
    if r['op'] in ('spawn','spawn_stubborn'):
        code='import time;time.sleep(20)' if r['op']=='spawn' else 'import signal,time;signal.signal(signal.SIGTERM,signal.SIG_IGN);print("ready",flush=True);time.sleep(20)'
        child=subprocess.Popen([sys.executable,'-c',code],stdout=subprocess.PIPE if r['op']=='spawn_stubborn' else None)
        if r['op']=='spawn_stubborn': child.stdout.readline()
        print(json.dumps({'id':r['id'],'ok':True,'child':child.pid}),flush=True);continue
    print(json.dumps({'id':r['id'],'ok':True,'result':{'id':r['op']}}),flush=True)
    if held:
        print(json.dumps({'event':'snapshot','topic':'clipboard','revision':1,'items':[],'initial':True,'cached':False,'replayed':True,'changed':[]}),flush=True)
        print(json.dumps({'id':held['id'],'ok':True,'result':{'id':'held-job'}}),flush=True);held=None
"""#
        try Data(fixture.utf8).write(to: script)
        let transport = PedroContinuityTransport()
        var events = [String]()
        transport.onEvent = { data in
            if let frame = try? JSONDecoder().decode(PedroContinuityPayload.self, from: data) { events.append(frame["event"]?.string ?? "") }
        }
        transport.start(script: script, config: directory.appendingPathComponent("unused.json"))
        defer { transport.stop() }
        async let first = transport.request(["op": .string("hold")], timeout: 5)
        try await Task.sleep(for: .milliseconds(50))
        let second = try await transport.request(["op": .string("second")], timeout: 5)
        let held = try await first
        precondition(second["result"]?.object["id"]?.string == "second")
        precondition(held["result"]?.object["id"]?.string == "held-job")
        precondition(events.contains("connection") && events.contains("snapshot"))
        let childReply = try await transport.request(["op": .string("spawn")], timeout: 5)
        let childPID = pid_t(childReply["child"]?.number ?? 0)
        precondition(childPID > 0 && kill(childPID, 0) == 0)
        let waiting = Task { try await transport.request(["op": .string("wait")], timeout: 10) }
        try await Task.sleep(for: .milliseconds(30))
        transport.stop()
        do { _ = try await waiting.value; fatalError("Stop must fail pending request") } catch { }
        for _ in 0..<20 {
            if kill(childPID, 0) != 0 { break }
            try await Task.sleep(for: .milliseconds(50))
        }
        precondition(kill(childPID, 0) != 0, "Owned SSH-equivalent descendant must terminate")
        // Restart uses a new process/session and continues correlating nested ids.
        transport.start(script: script, config: directory.appendingPathComponent("unused.json"))
        let restarted = try await transport.request(["op": .string("restart")], timeout: 5)
        precondition(restarted["result"]?.object["id"]?.string == "restart")
        // A crashed group leader must not hide surviving descendants. SIGTERM is
        // deliberately ignored to require escalation even though the leader is dead.
        for stopAfterCrash in [false, true] {
            let stubborn = try await transport.request(["op": .string("spawn_stubborn")], timeout: 5)
            let descendant = pid_t(stubborn["child"]?.number ?? 0)
            precondition(descendant > 0 && kill(descendant, 0) == 0)
            var replacementObserved = false
            var descendantAtReplacement = false
            var offlineObserved = false
            transport.onEvent = { data in
                guard let frame = try? JSONDecoder().decode(PedroContinuityPayload.self, from: data), frame["event"]?.string == "connection" else { return }
                if frame["state"]?.string == "offline" {
                    let firstOffline = !offlineObserved
                    offlineObserved = true
                    if stopAfterCrash && firstOffline { transport.stop() }
                } else if frame["state"]?.string == "online" && offlineObserved {
                    replacementObserved = true
                    descendantAtReplacement = kill(descendant, 0) == 0
                }
            }
            // The EOF/crash must fail the outstanding correlated request promptly.
            do { _ = try await transport.request(["op": .string("crash")], timeout: 5); fatalError("Crash must fail pending request") } catch { }
            for _ in 0..<100 {
                if offlineObserved && kill(descendant, 0) != 0 && (stopAfterCrash || replacementObserved) { break }
                try await Task.sleep(for: .milliseconds(50))
            }
            let alive = kill(descendant, 0) == 0
            if alive { kill(descendant, SIGKILL) } // A failing regression never leaves its fixture behind.
            precondition(offlineObserved && !alive, "Crash cleanup must kill descendants after leader exit")
            precondition(!descendantAtReplacement, "Replacement must wait for owned-group cleanup")
            if stopAfterCrash { precondition(!replacementObserved, "Explicit stop must suppress crash restart") }
            else {
                precondition(replacementObserved, "Transport must restart after crash cleanup")
                let reply = try await transport.request(["op": .string("after-crash")], timeout: 5)
                precondition(reply["result"]?.object["id"]?.string == "after-crash")
            }
        }
        print("PASS: out-of-order replies, unsolicited event, stderr drain, orderly shutdown, crash escalation after leader exit, cleanup before replacement, stop during crash cleanup, restart")
    }
}
